// Command genlua writes the --lua-desync allow-list from the pinned engine's Lua files.
//
//	go run ./genlua -engine v1.0.6 -o luafuncs_gen.go <file.lua>...
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"slices"
)

// Desync functions are global, column-0 declarations.
var declRe = regexp.MustCompile(`^function ([a-z_0-9]+)\(ctx, desync\)$`)

func main() {
	engine := flag.String("engine", "", "engine version the Lua files come from")
	out := flag.String("o", "", "output Go file")
	flag.Parse()
	if *engine == "" || *out == "" || flag.NArg() == 0 {
		log.Fatal("usage: genlua -engine VERSION -o FILE file.lua...")
	}
	var funcs []string
	for _, f := range flag.Args() {
		names, err := scan(f)
		if err != nil {
			log.Fatal(err)
		}
		if len(names) == 0 {
			log.Fatalf("%s: no desync functions found", f)
		}
		funcs = append(funcs, names...)
	}
	slices.Sort(funcs)
	funcs = slices.Compact(funcs)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by genlua; DO NOT EDIT.\n// Source: zapret2 %s", *engine)
	for _, f := range flag.Args() {
		fmt.Fprintf(&b, " %s", filepath.Base(f))
	}
	fmt.Fprintf(&b, "\n\npackage presets\n\nconst LuaFuncsEngine = %q\n\nvar LuaFuncs = map[string]bool{\n", *engine)
	for _, n := range funcs {
		fmt.Fprintf(&b, "%q: true,\n", n)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func scan(name string) ([]string, error) {
	f, err := os.Open(name)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var names []string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		if m := declRe.FindStringSubmatch(sc.Text()); m != nil {
			names = append(names, m[1])
		}
	}
	return names, sc.Err()
}
